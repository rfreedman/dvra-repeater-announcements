"""Guard defer/nudge timing constants used by fire and scheduler (GitHub #3)."""

from app.fire import (
    DEFER_CLEAR_NONBLOCKING_MAX_SECONDS,
    DEFER_RETRY_WHEN_CLEAR_MET_CAP_SECONDS,
)
from app.scheduler import (
    MANUAL_NUDGE_MIN_WAIT_FOR_UNKNOWN_KIND_SECONDS,
    MANUAL_NUDGE_PTT_TIMER_PROTECT_SECONDS,
    MANUAL_NUDGE_RUN_DELAY_MS,
    MANUAL_NUDGE_SKIP_IF_RUN_WITHIN_SECONDS,
    SCHEDULER_MIN_WAKE_SECONDS,
)


def test_defer_timing_constants_unchanged():
    assert DEFER_CLEAR_NONBLOCKING_MAX_SECONDS == 0.5
    assert DEFER_RETRY_WHEN_CLEAR_MET_CAP_SECONDS == 1.0
    assert SCHEDULER_MIN_WAKE_SECONDS == 0.5
    assert MANUAL_NUDGE_SKIP_IF_RUN_WITHIN_SECONDS == 0.2
    assert MANUAL_NUDGE_PTT_TIMER_PROTECT_SECONDS == 2.0
    assert MANUAL_NUDGE_MIN_WAIT_FOR_UNKNOWN_KIND_SECONDS == 2.0
    assert MANUAL_NUDGE_RUN_DELAY_MS == 50
